/// Returns the 8-row glyph for `byte`, or the blank space cell when `byte`
/// falls outside the embedded printable range.
fn glyph(byte: u8) -> &'static [u8; 8] {
    if (FIRST_GLYPH..=LAST_GLYPH).contains(&byte) {
        &FONT[(byte - FIRST_GLYPH) as usize]
    } else {
        // U+0020 (space) — a blank cell for control and non-ASCII bytes.
        &FONT[0]
    }
}

/// A line-oriented text console over a [`Framebuffer`].
///
/// The cursor tracks the next cell in glyph units. [`Console::print`] is the
/// only sink; it renders printable bytes and interprets `\n`/`\r`.
pub struct Console {
    fb: Framebuffer,
    /// Cursor column in glyph cells.
    col: u32,
    /// Cursor row in glyph cells.
    row: u32,
    /// Columns that fit the surface (`fb.width() / GLYPH_W`).
    cols: u32,
    /// Rows that fit the surface (`fb.height() / GLYPH_H`).
    rows: u32,
    /// Foreground (glyph) pixel, `0x00RRGGBB`.
    fg: u32,
    /// Background (cell) pixel, `0x00RRGGBB`.
    bg: u32,
}

impl Console {
    /// Builds a console over `fb` with the given foreground/background colors
    /// and clears the whole surface to the background.
    #[must_use]
    pub fn new(fb: Framebuffer, fg: u32, bg: u32) -> Self {
        let cols = fb.width() / GLYPH_W;
        let rows = fb.height() / GLYPH_H;
        fb.clear(bg);
        Self {
            fb,
            col: 0,
            row: 0,
            cols,
            rows,
            fg,
            bg,
        }
    }

    /// Renders `s` at the cursor, advancing one cell per byte. `\n` moves to
    /// the start of the next row, `\r` returns to column 0, and any other byte
    /// renders a cell (printable ASCII as its glyph, everything else blank).
    pub fn print(&mut self, s: &str) {
        for &byte in s.as_bytes() {
            self.put_byte(byte);
        }
    }

    /// Renders one byte and advances the cursor, wrapping at the row edge.
    fn put_byte(&mut self, byte: u8) {
        match byte {
            b'\n' => self.newline(),
            b'\r' => self.col = 0,
            _ => {
                self.draw_cell(byte);
                self.col += 1;
                if self.col >= self.cols {
                    self.newline();
                }
            }
        }
    }

    /// Moves the cursor to the start of the next row, wrapping to the top when
    /// the surface is full (the splash log fits, so no scrollback is needed).
    const fn newline(&mut self) {
        self.col = 0;
        self.row += 1;
        if self.row >= self.rows {
            self.row = 0;
        }
    }

    /// Blits the glyph for `byte` into the current cell.
    fn draw_cell(&self, byte: u8) {
        let rows = glyph(byte);
        let x0 = self.col * GLYPH_W;
        let y0 = self.row * GLYPH_H;
        for (gy, &bits) in rows.iter().enumerate() {
            for gx in 0..GLYPH_W {
                // Bit 0 is the leftmost pixel in the font8x8 encoding.
                let on = (bits >> gx) & 1 != 0;
                let color = if on { self.fg } else { self.bg };
                // `gy` is 0..8, so the cast into the pixel coordinate is
                // value-preserving.
                #[allow(clippy::cast_possible_truncation)]
                self.fb.put_pixel(x0 + gx, y0 + gy as u32, color);
            }
        }
    }
}
