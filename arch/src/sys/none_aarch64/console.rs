//! 8x8 bitmap-font text console over the `VideoCore` framebuffer.
//!
//! [`super::framebuffer::Framebuffer`] exposes only raw pixel stores. This
//! module turns that surface into a line-oriented text console so the
//! bare-metal boot log is legible on the HDMI output, not only on the UART.
//! It owns a cursor (column/row in glyph cells), renders each printable ASCII
//! byte from an embedded 8x8 glyph table, and advances/wraps as bytes arrive.
//!
//! Scope is the splash floor: one fixed foreground/background pair, no
//! scrollback (the boot log fits the surface), and no escape-sequence
//! parsing. The glyph table is the public-domain `font8x8` basic-latin set
//! (CC0, Daniel Hepper) embedded as our own data over the printable range
//! U+0020..=U+007F — not a third-party dependency.

