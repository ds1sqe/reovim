//! Product-facing executable source-install syscall vocabulary.
//!
//! This leaf owns source-domain install controls for `/bin` and `/payload`
//! source artifacts. The raw syscall leaf remains only the transport spine,
//! while source inventory remains fd-readable through `/proc/sources` and
//! `/proc/media`.

#![no_std]

use {
    core::mem::size_of,
    reovim_uapi_syscall::{RawSyscall, SyscallArgs, SyscallError, SyscallNr},
};

/// Maximum source artifact name bytes retained in an install report.
pub const SOURCE_REPORT_NAME_BYTES: usize = 32;
/// Maximum source-store path bytes retained in an install report.
pub const SOURCE_REPORT_PATH_BYTES: usize = 64;
/// Maximum source-media storage label bytes retained in an install report.
pub const SOURCE_REPORT_STORAGE_BYTES: usize = 32;

/// Source-install control operation.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
#[repr(transparent)]
pub struct SourceControlOp(usize);

impl SourceControlOp {
    /// Install a status-only `/bin` source image.
    pub const INSTALL_BIN_STATUS: Self = Self(0);
    /// Install a status-only `/payload` source image.
    pub const INSTALL_PAYLOAD_STATUS: Self = Self(1);
    /// Install a `/bin` source image from checked source media.
    pub const INSTALL_BIN_MEDIA: Self = Self(2);
    /// Install a `/payload` source image from checked source media.
    pub const INSTALL_PAYLOAD_MEDIA: Self = Self(3);

    /// Builds a control op from a raw transport scalar.
    #[must_use]
    pub const fn new(raw: usize) -> Self {
        Self(raw)
    }

    /// Returns the raw transport scalar.
    #[must_use]
    pub const fn raw(self) -> usize {
        self.0
    }
}

