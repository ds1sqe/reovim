/// Structured result of a source-install control operation.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[repr(C)]
pub struct SourceInstallReport {
    namespace: usize,
    status: usize,
    origin: usize,
    bytes_len: usize,
    storage_capacity_bytes: usize,
    artifact_bytes_len: usize,
    checksum: u32,
    name_len: usize,
    name_truncated: u8,
    path_len: usize,
    path_truncated: u8,
    storage_len: usize,
    storage_truncated: u8,
    name: [u8; SOURCE_REPORT_NAME_BYTES],
    path: [u8; SOURCE_REPORT_PATH_BYTES],
    storage: [u8; SOURCE_REPORT_STORAGE_BYTES],
}

impl SourceInstallReport {
    /// Empty report value used before a source-install request is issued.
    #[must_use]
    pub const fn empty() -> Self {
        Self {
            namespace: SourceNamespaceCode::NONE.raw(),
            status: SourceInstallStatusCode::NONE.raw(),
            origin: SourceInstallOriginCode::NONE.raw(),
            bytes_len: 0,
            storage_capacity_bytes: 0,
            artifact_bytes_len: 0,
            checksum: 0,
            name_len: 0,
            name_truncated: 0,
            path_len: 0,
            path_truncated: 0,
            storage_len: 0,
            storage_truncated: 0,
            name: [0; SOURCE_REPORT_NAME_BYTES],
            path: [0; SOURCE_REPORT_PATH_BYTES],
            storage: [0; SOURCE_REPORT_STORAGE_BYTES],
        }
    }

    /// Clears this report to the empty value.
    pub fn clear(&mut self) {
        *self = Self::empty();
    }

    /// Records the source namespace.
    pub fn set_namespace(&mut self, namespace: SourceNamespaceCode) {
        self.namespace = namespace.raw();
    }

    /// Records the install status.
    pub fn set_status(&mut self, status: SourceInstallStatusCode) {
        self.status = status.raw();
    }

    /// Records the install origin.
    pub fn set_origin(&mut self, origin: SourceInstallOriginCode) {
        self.origin = origin.raw();
    }

    /// Records the installed source byte count.
    pub fn set_bytes_len(&mut self, bytes_len: usize) {
        self.bytes_len = bytes_len;
    }

    /// Records the source-media storage capacity.
    pub fn set_storage_capacity_bytes(&mut self, capacity: usize) {
        self.storage_capacity_bytes = capacity;
    }

    /// Records the checked source-media artifact byte count.
    pub fn set_artifact_bytes_len(&mut self, bytes_len: usize) {
        self.artifact_bytes_len = bytes_len;
    }

    /// Records the checked source payload checksum.
    pub fn set_checksum(&mut self, checksum: u32) {
        self.checksum = checksum;
    }

    /// Records the canonical source artifact name.
    pub fn set_name(&mut self, name: &str) {
        let (len, truncated) = copy_truncated(name.as_bytes(), &mut self.name);
        self.name_len = len;
        self.name_truncated = u8::from(truncated);
    }

    /// Records the source-store path.
    pub fn set_path(&mut self, path: &str) {
        let (len, truncated) = copy_truncated(path.as_bytes(), &mut self.path);
        self.path_len = len;
        self.path_truncated = u8::from(truncated);
    }

    /// Records the source-media storage label.
    pub fn set_storage(&mut self, storage: &str) {
        let (len, truncated) = copy_truncated(storage.as_bytes(), &mut self.storage);
        self.storage_len = len;
        self.storage_truncated = u8::from(truncated);
    }

    /// Returns the source namespace.
    #[must_use]
    pub const fn namespace(self) -> SourceNamespaceCode {
        SourceNamespaceCode::new(self.namespace)
    }

    /// Returns the install status.
    #[must_use]
    pub const fn status(self) -> SourceInstallStatusCode {
        SourceInstallStatusCode::new(self.status)
    }

    /// Returns the install origin.
    #[must_use]
    pub const fn origin(self) -> SourceInstallOriginCode {
        SourceInstallOriginCode::new(self.origin)
    }

    /// Returns the installed source byte count.
    #[must_use]
    pub const fn bytes_len(self) -> usize {
        self.bytes_len
    }

    /// Returns the source-media storage capacity.
    #[must_use]
    pub const fn storage_capacity_bytes(self) -> usize {
        self.storage_capacity_bytes
    }

    /// Returns the checked source-media artifact byte count.
    #[must_use]
    pub const fn artifact_bytes_len(self) -> usize {
        self.artifact_bytes_len
    }

    /// Returns the checked source payload checksum.
    #[must_use]
    pub const fn checksum(self) -> u32 {
        self.checksum
    }

    /// Returns the canonical source artifact name bytes.
    #[must_use]
    pub fn name_bytes(&self) -> &[u8] {
        &self.name[..self.name_len]
    }

    /// Returns whether the source artifact name was truncated.
    #[must_use]
    pub const fn name_truncated(self) -> bool {
        self.name_truncated != 0
    }

    /// Returns the source-store path bytes.
    #[must_use]
    pub fn path_bytes(&self) -> &[u8] {
        &self.path[..self.path_len]
    }

    /// Returns whether the source-store path was truncated.
    #[must_use]
    pub const fn path_truncated(self) -> bool {
        self.path_truncated != 0
    }

    /// Returns the source-media storage label bytes.
    #[must_use]
    pub fn storage_bytes(&self) -> &[u8] {
        &self.storage[..self.storage_len]
    }

    /// Returns whether the source-media storage label was truncated.
    #[must_use]
    pub const fn storage_truncated(self) -> bool {
        self.storage_truncated != 0
    }
}

/// Product-facing source syscall error.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
#[repr(transparent)]
pub struct SourceError(i32);

impl SourceError {
    /// The requested arguments are not valid for this operation.
    pub const INVALID_ARGUMENT: Self = Self(SyscallError::INVALID_ARGUMENT.code());
    /// This kernel build does not support the requested operation.
    pub const UNSUPPORTED: Self = Self(SyscallError::UNSUPPORTED.code());
    /// No matching source-backed `/bin` or `/payload` descriptor exists.
    pub const NOT_FOUND: Self = Self(SyscallError::NOT_FOUND.code());
    /// The syscall requires an attached current process context.
    pub const NO_CURRENT_PROCESS: Self = Self(SyscallError::NO_CURRENT_PROCESS.code());
    /// The source-media or source-store operation failed.
    pub const IO: Self = Self(SyscallError::IO.code());
    /// The source artifact exceeded the bounded runtime overlay.
    pub const FILE_TOO_LARGE: Self = Self(SyscallError::FILE_TOO_LARGE.code());
    /// No runtime source overlay slot was available.
    pub const BUSY: Self = Self(SyscallError::BUSY.code());
    /// The requested source image failed validation.
    pub const INVALID_IMAGE: Self = Self(SyscallError::INVALID_IMAGE.code());
    /// No source-media target is installed.
    pub const SOURCE_MEDIA_UNAVAILABLE: Self = Self(SyscallError::SOURCE_MEDIA_UNAVAILABLE.code());
    /// The source-media target failed to read a bounded artifact.
    pub const SOURCE_MEDIA_READ_FAILED: Self = Self(SyscallError::SOURCE_MEDIA_READ_FAILED.code());
    /// Source-media artifact namespace does not match the requested install kind.
    pub const SOURCE_MEDIA_NAMESPACE_MISMATCH: Self =
        Self(SyscallError::SOURCE_MEDIA_NAMESPACE_MISMATCH.code());
    /// Source-media artifact path does not match the requested descriptor.
    pub const SOURCE_MEDIA_PATH_MISMATCH: Self =
        Self(SyscallError::SOURCE_MEDIA_PATH_MISMATCH.code());

    /// Builds a source error from a transport code.
    #[must_use]
    pub const fn new(code: i32) -> Self {
        Self(code)
    }

    /// Returns the stable transport code.
    #[must_use]
    pub const fn code(self) -> i32 {
        self.0
    }
}

/// Source-install control backed by the raw Reovim syscall transport.
#[derive(Debug, Clone, Copy)]
pub struct SyscallSourceControl {
    raw: RawSyscall,
}

impl SyscallSourceControl {
    /// Creates a source control adapter over the raw syscall transport.
    #[must_use]
    pub const fn new(raw: RawSyscall) -> Self {
        Self { raw }
    }

    /// Installs a status-only `/bin` source image.
    ///
    /// # Errors
    ///
    /// Returns [`SourceError`] when `name` is empty, the status is not
    /// [`SourceInstallStatusCode::OK`] or [`SourceInstallStatusCode::ERROR`],
    /// or the kernel rejects the install request.
    pub fn install_bin_status(
        self,
        name: &str,
        status: SourceInstallStatusCode,
    ) -> Result<SourceInstallReport, SourceError> {
        if status != SourceInstallStatusCode::OK && status != SourceInstallStatusCode::ERROR {
            return Err(SourceError::INVALID_ARGUMENT);
        }
        self.install_report(SourceControlOp::INSTALL_BIN_STATUS, name, status)
    }

    /// Installs a status-only `/payload` source image.
    ///
    /// # Errors
    ///
    /// Returns [`SourceError`] when `name` is empty, the status is not
    /// [`SourceInstallStatusCode::READY`] or [`SourceInstallStatusCode::FAILED`],
    /// or the kernel rejects the install request.
    pub fn install_payload_status(
        self,
        name: &str,
        status: SourceInstallStatusCode,
    ) -> Result<SourceInstallReport, SourceError> {
        if status != SourceInstallStatusCode::READY && status != SourceInstallStatusCode::FAILED {
            return Err(SourceError::INVALID_ARGUMENT);
        }
        self.install_report(SourceControlOp::INSTALL_PAYLOAD_STATUS, name, status)
    }

    /// Installs a `/bin` source image from checked source media.
    ///
    /// # Errors
    ///
    /// Returns [`SourceError`] when `name` is empty or the kernel rejects the
    /// source-media install request.
    pub fn install_bin_media(self, name: &str) -> Result<SourceInstallReport, SourceError> {
        self.install_report(SourceControlOp::INSTALL_BIN_MEDIA, name, SourceInstallStatusCode::NONE)
    }

    /// Installs a `/payload` source image from checked source media.
    ///
    /// # Errors
    ///
    /// Returns [`SourceError`] when `name` is empty or the kernel rejects the
    /// source-media install request.
    pub fn install_payload_media(self, name: &str) -> Result<SourceInstallReport, SourceError> {
        self.install_report(
            SourceControlOp::INSTALL_PAYLOAD_MEDIA,
            name,
            SourceInstallStatusCode::NONE,
        )
    }

    fn install_report(
        self,
        op: SourceControlOp,
        name: &str,
        status: SourceInstallStatusCode,
    ) -> Result<SourceInstallReport, SourceError> {
        if name.is_empty() {
            return Err(SourceError::INVALID_ARGUMENT);
        }
        let mut report = SourceInstallReport::empty();
        self.raw
            .invoke(
                SyscallNr::SOURCE_CONTROL,
                SyscallArgs::new([
                    op.raw(),
                    name.as_ptr().addr(),
                    name.len(),
                    status.raw(),
                    (&raw mut report).addr(),
                    size_of::<SourceInstallReport>(),
                ]),
            )
            .decode()
            .map(|_| report)
            .map_err(source_error_from_syscall)
    }
}

fn copy_truncated(src: &[u8], dst: &mut [u8]) -> (usize, bool) {
    dst.fill(0);
    let len = src.len().min(dst.len());
    dst[..len].copy_from_slice(&src[..len]);
    (len, len < src.len())
}

fn source_error_from_syscall(error: SyscallError) -> SourceError {
    SourceError::new(error.code())
}
